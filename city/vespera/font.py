def text_mask(s, scale=2):
    s = s.upper()
    rows = 7 * scale
    cols = len(s) * 6 * scale
    m = np.zeros((rows, cols), bool)
    for k, ch in enumerate(s):
        g = G.get(ch, G[" "]).split()
        for r, line in enumerate(g):
            for c, v in enumerate(line):
                if v == "1":
                    m[r * scale:(r + 1) * scale, (k * 6 + c) * scale:(k * 6 + c + 1) * scale] = True
    return m


def draw(img, s, x, y, scale=2, color=(1, 1, 1), shadow=True, center=True):
    m = text_mask(s, scale)
    h, w = m.shape
    if center:
        x -= w // 2
        y -= h // 2
    H, W_ = img.shape[:2]
    for off, col in (((1, 1), (0, 0, 0)), ((0, 0), color)) if shadow else (((0, 0), color),):
        yy, xx = np.nonzero(m)
        yy = yy + y + off[1]
        xx = xx + x + off[0]
        ok = (yy >= 0) & (yy < H) & (xx >= 0) & (xx < W_)
        img[yy[ok], xx[ok]] = col
